safe_csv <- function(path) {
  if (!file.exists(path)) return(NULL)
  dat <- tryCatch(read.csv(path, check.names = FALSE, stringsAsFactors = FALSE), error = function(e) NULL)
  if (is.null(dat)) return(NULL)
  if (ncol(dat) > 1) {
    first <- dat[[1]]
    first_name <- names(dat)[1] %||% ""
    looks_like_row_index <- !nzchar(first_name) || first_name %in% c("X", "...1")
    if (!anyDuplicated(first) && (looks_like_row_index || !all(suppressWarnings(!is.na(as.numeric(first)))))) {
      dat <- dat[-1]
      rownames(dat) <- first
    }
  }
  dat
}

clean_predictors <- function(df) {
  if (is.null(df)) return(NULL)
  df <- as.data.frame(df, stringsAsFactors = FALSE, check.names = FALSE)
  for (nm in names(df)) {
    if (is.character(df[[nm]])) {
      x <- trimws(df[[nm]])
      numeric_x <- suppressWarnings(as.numeric(x))
      if (all(is.na(x) | !nzchar(x) | !is.na(numeric_x))) {
        df[[nm]] <- numeric_x
      } else {
        df[[nm]] <- as.factor(x)
      }
    } else if (is.logical(df[[nm]])) {
      df[[nm]] <- as.factor(df[[nm]])
    }
  }
  df
}

numeric_matrix <- function(df, label) {
  if (is.null(df)) stop(label, " is missing.", call. = FALSE)
  raw <- as.matrix(df)
  vals <- suppressWarnings(as.numeric(raw))
  mat <- matrix(vals, nrow = nrow(raw), ncol = ncol(raw), dimnames = dimnames(raw))
  raw_chr <- trimws(as.character(raw))
  bad <- !is.na(raw_chr) & nzchar(raw_chr) & is.na(vals)
  if (any(bad)) stop(label, " contains non-numeric values.", call. = FALSE)
  mat
}

id_matrix <- function(df) {
  if (is.null(df)) return(NULL)
  out <- as.data.frame(df, stringsAsFactors = FALSE, check.names = FALSE)
  for (nm in names(out)) out[[nm]] <- as.integer(as.factor(out[[nm]]))
  mat <- as.matrix(out)
  storage.mode(mat) <- "integer"
  mat
}

normalize_family <- function(x) {
  x <- tolower(trimws(as.character(x)))
  x[x == "lognormal"] <- "lnormal"
  x
}

parse_family <- function(Y, cfg) {
  model <- cfg$model %||% list()
  txt <- trimws(model$family_vector_override %||% "")
  if (nzchar(txt)) {
    fam <- normalize_family(unlist(strsplit(txt, ",")))
  } else {
    fam <- normalize_family(model$family %||% "negative.binomial")
  }
  fam <- fam[nzchar(fam)]
  if (length(fam) == 1) fam <- rep(fam, ncol(Y))
  fam
}

normalize_lv_type <- function(x) {
  x <- trimws(as.character(x %||% "independent"))
  if (identical(x, "power.exponential")) x <- "powered.exponential"
  x
}

parse_numeric_vector <- function(x, default = NULL) {
  txt <- trimws(as.character(x %||% ""))
  if (!nzchar(txt)) return(default)
  vals <- suppressWarnings(as.numeric(trimws(unlist(strsplit(txt, ",")))))
  vals[is.finite(vals)]
}

make_design <- function(X, formula_text) {
  if (is.null(X)) return(NULL)
  formula_text <- trimws(formula_text %||% "~ .")
  if (!nzchar(formula_text)) formula_text <- "~ ."
  mm <- model.matrix(as.formula(formula_text), data = X)
  intercept <- which(colnames(mm) == "(Intercept)")
  if (length(intercept) > 0) mm <- mm[, -intercept, drop = FALSE]
  mm
}

parse_xind <- function(text, S, P) {
  txt <- trimws(text %||% "")
  if (!nzchar(txt) || is.null(P) || P == 0) return(NULL)
  rows <- strsplit(txt, ";", fixed = TRUE)[[1]]
  mat <- do.call(rbind, lapply(rows, function(r) {
    suppressWarnings(as.numeric(trimws(unlist(strsplit(r, ",")))))
  }))
  if (nrow(mat) == 1 && length(mat) == P) mat <- matrix(rep(mat, each = S), nrow = S, byrow = FALSE)
  if (length(mat) == S * P) mat <- matrix(as.numeric(mat), nrow = S, ncol = P, byrow = TRUE)
  if (!all(dim(mat) == c(S, P))) stop("X.ind must be a 0/1 matrix with ncol(Y) rows and ncol(model.matrix(formula.X, X)) columns.", call. = FALSE)
  if (!all(mat %in% c(0, 1))) stop("X.ind values must be 0/1.", call. = FALSE)
  mat
}

parse_traits <- function(traits) {
  if (is.null(traits)) return(NULL)
  tr <- clean_predictors(traits)
  mm <- model.matrix(~ ., data = tr)
  intercept <- which(colnames(mm) == "(Intercept)")
  if (length(intercept) > 0) mm <- mm[, -intercept, drop = FALSE]
  if (ncol(mm) == 0) stop("traits.csv produced zero usable trait columns after encoding.", call. = FALSE)
  mm
}

parse_which_traits <- function(text, n_traits, n_x) {
  if (is.null(n_traits) || n_traits < 1) return(NULL)
  txt <- trimws(text %||% "")
  if (!nzchar(txt)) return(rep(list(seq_len(n_traits)), n_x + 1))
  groups <- strsplit(txt, ";", fixed = TRUE)[[1]]
  out <- lapply(groups, function(g) {
    vals <- suppressWarnings(as.integer(trimws(unlist(strsplit(g, ",")))))
    vals[is.finite(vals)]
  })
  if (length(out) == 1 && length(out[[1]]) > 0) out <- rep(out, n_x + 1)
  if (length(out) != n_x + 1) stop("which.traits must contain 1+ncol(X) semicolon-separated groups.", call. = FALSE)
  out
}

parse_ssvs_index <- function(text, use_ssvs, n_x) {
  if (!isTRUE(use_ssvs) || is.null(n_x) || n_x == 0) return(-1)
  vals <- suppressWarnings(as.integer(parse_numeric_vector(text, default = 0)))
  if (length(vals) == 0) vals <- 0
  if (length(vals) == 1) vals <- rep(vals, n_x)
  if (length(vals) != n_x) stop("prior.control$ssvs.index must have length 1 or ncol(X).", call. = FALSE)
  vals
}

parse_ssvs_traitsindex <- function(text, use_ssvs, which_traits) {
  if (!isTRUE(use_ssvs) || is.null(which_traits)) return(-1)
  txt <- trimws(text %||% "")
  if (!nzchar(txt)) {
    return(lapply(which_traits, function(z) if (length(z) == 1 && z[[1]] == 0) -1L else rep(0L, length(z))))
  }
  groups <- strsplit(txt, ";", fixed = TRUE)[[1]]
  out <- lapply(groups, function(g) {
    vals <- suppressWarnings(as.integer(trimws(unlist(strsplit(g, ",")))))
    vals[is.finite(vals)]
  })
  if (length(out) != length(which_traits)) stop("prior.control$ssvs.traitsindex must match which.traits length.", call. = FALSE)
  out
}

parse_trial_size <- function(trials, scalar, S) {
  if (is.null(trials)) {
    val <- suppressWarnings(as.numeric(scalar %||% 1))
    if (!is.finite(val) || val < 1) stop("trial.size must be positive.", call. = FALSE)
    return(val)
  }
  mat <- numeric_matrix(trials, "trial.size.csv")
  vals <- as.numeric(mat)
  vals <- vals[is.finite(vals)]
  if (length(vals) == 1) return(vals)
  if (length(vals) == S) return(vals)
  if (ncol(mat) == S) {
    per_col <- apply(mat, 2, function(z) unique(z[is.finite(z)]))
    if (all(vapply(per_col, length, integer(1)) == 1)) return(as.numeric(per_col))
  }
  stop("trial.size.csv must contain one value or one value per response/species.", call. = FALSE)
}

flatten_matrix <- function(x, value_name = "value") {
  if (is.null(x)) return(data.frame())
  if (is.list(x) && !is.data.frame(x)) {
    if (!is.null(x$out)) return(flatten_matrix(x$out, value_name = value_name))
    parts <- lapply(names(x), function(nm) {
      if (is.null(x[[nm]])) return(NULL)
      dat <- flatten_matrix(x[[nm]], value_name = value_name)
      if (!nrow(dat)) return(NULL)
      data.frame(component = nm, dat, stringsAsFactors = FALSE)
    })
    parts <- Filter(Negate(is.null), parts)
    if (length(parts) == 0) return(data.frame())
    all_names <- unique(unlist(lapply(parts, names)))
    parts <- lapply(parts, function(dat) {
      missing <- setdiff(all_names, names(dat))
      for (nm in missing) dat[[nm]] <- NA
      dat[, all_names, drop = FALSE]
    })
    return(do.call(rbind, parts))
  }
  if (is.data.frame(x)) return(x)
  if (is.vector(x) && is.null(dim(x))) {
    return(data.frame(name = names(x) %||% seq_along(x), value = as.numeric(x), stringsAsFactors = FALSE))
  }
  arr <- as.array(x)
  idx <- as.data.frame.table(arr, responseName = value_name, stringsAsFactors = FALSE)
  idx
}

