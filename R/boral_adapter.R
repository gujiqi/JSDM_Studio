fit_or_fail <- tryCatch({
  if (is.null(Y)) stop("Y.csv is required.", call. = FALSE)
  Ymat <- numeric_matrix(Y, "Y.csv")
  X_clean <- clean_predictors(X_raw)
  X_design <- make_design(X_clean, model_cfg$formula.X %||% "~ .")
  fam <- parse_family(Ymat, cfg)
  allowed <- c("negative.binomial", "ztnegative.binomial", "poisson", "ztpoisson", "binomial",
               "normal", "lnormal", "tweedie", "ordinal", "exponential", "gamma", "beta")
  bad <- setdiff(fam, allowed)
  if (length(bad) > 0) stop("Unsupported boral family value(s): ", paste(unique(bad), collapse = ", "), call. = FALSE)
  if (length(fam) != ncol(Ymat)) stop("Family vector must have length one or ncol(Y).", call. = FALSE)
  trial_size <- parse_trial_size(trials_raw, model_cfg$trial.size %||% 1, ncol(Ymat))
  for (j in seq_len(ncol(Ymat))) {
    yj <- Ymat[, j]
    fj <- fam[[j]]
    if (fj == "binomial") {
      tj <- if (length(trial_size) == 1) trial_size else trial_size[[j]]
      if (any(yj < 0 | abs(yj - round(yj)) > 1e-8 | yj > tj, na.rm = TRUE)) stop("binomial Y must be integer successes between 0 and trial.size.", call. = FALSE)
    }
    if (fj %in% c("poisson", "negative.binomial") && any(yj < 0 | abs(yj - round(yj)) > 1e-8, na.rm = TRUE)) stop(fj, " responses must be non-negative integers.", call. = FALSE)
    if (fj %in% c("ztpoisson", "ztnegative.binomial") && any(yj < 1 | abs(yj - round(yj)) > 1e-8, na.rm = TRUE)) stop(fj, " responses must be positive integers.", call. = FALSE)
    if (fj %in% c("beta") && any(yj <= 0 | yj >= 1, na.rm = TRUE)) stop("beta responses must be strictly between 0 and 1.", call. = FALSE)
    if (fj %in% c("gamma", "exponential", "lnormal") && any(yj <= 0, na.rm = TRUE)) stop(fj, " responses must be positive.", call. = FALSE)
    if (fj == "ordinal" && any(yj < 1 | abs(yj - round(yj)) > 1e-8, na.rm = TRUE)) stop("ordinal responses must be positive integer levels.", call. = FALSE)
  }
  if (!is.null(X_clean) && nrow(X_clean) != nrow(Ymat)) stop("XData.csv rows must match Y.csv rows.", call. = FALSE)
  if (!is.null(newdata_raw)) {
    new_clean <- clean_predictors(newdata_raw)
    missing_new <- setdiff(names(X_clean %||% data.frame()), names(new_clean))
    if (length(missing_new) > 0) stop("newdata.csv is missing XData columns: ", paste(missing_new, collapse = ", "), call. = FALSE)
  }
  lv_type <- normalize_lv_type((model_cfg$lv.control %||% list())$type %||% "independent")
  num_lv <- as.integer((model_cfg$lv.control %||% list())$num.lv %||% 0)
  if (!is.finite(num_lv) || num_lv < 0) stop("num.lv must be >= 0.", call. = FALSE)
  distmat <- if (!is.null(distmat_raw)) numeric_matrix(distmat_raw, "distmat.csv") else NULL
  if (lv_type != "independent") {
    if (is.null(distmat)) stop("Structured latent variables require distmat.csv.", call. = FALSE)
    if (!all(dim(distmat) == c(nrow(Ymat), nrow(Ymat)))) stop("distmat.csv must be nrow(Y) by nrow(Y).", call. = FALSE)
  }
  lv_control <- list(num.lv = num_lv, type = lv_type, distmat = distmat)
  if (num_lv == 0) lv_control$type <- "independent"
  rowids <- id_matrix(rowids_raw)
  ranefids <- if (isTRUE(trait_cfg$use_ranef %||% FALSE)) id_matrix(ranefids_raw) else NULL
  if (!is.null(rowids) && nrow(rowids) != nrow(Ymat)) stop("row.ids.csv rows must match Y.csv rows.", call. = FALSE)
  if (!is.null(ranefids) && nrow(ranefids) != nrow(Ymat)) stop("ranef.ids.csv rows must match Y.csv rows.", call. = FALSE)
  offset <- if (isTRUE(model_cfg$use_offset %||% FALSE)) numeric_matrix(offset_raw, "offset.csv") else NULL
  if (!is.null(offset) && !all(dim(offset) == dim(Ymat))) stop("offset.csv must have the same dimensions as Y.csv.", call. = FALSE)
  traits <- if (isTRUE(trait_cfg$use_traits %||% FALSE)) parse_traits(traits_raw) else NULL
  if (!is.null(traits) && nrow(traits) != ncol(Ymat)) stop("traits.csv rows must match Y.csv columns/species.", call. = FALSE)
  which_traits <- parse_which_traits(trait_cfg$which.traits %||% "", if (is.null(traits)) NULL else ncol(traits), if (is.null(X_design)) 0 else ncol(X_design))
  ssvs_index <- parse_ssvs_index(trait_cfg$ssvs.index %||% "", isTRUE(trait_cfg$use_ssvs %||% FALSE) && is.null(traits), if (is.null(X_design)) 0 else ncol(X_design))
  ssvs_traitsindex <- parse_ssvs_traitsindex(trait_cfg$ssvs.traitsindex %||% "", isTRUE(trait_cfg$use_ssvs %||% FALSE) && !is.null(traits), which_traits)
  prior_type <- trimws(unlist(strsplit(mcmc_cfg$prior.type %||% "normal,normal,normal,uniform", ",")))
  hypparams <- suppressWarnings(as.numeric(trimws(unlist(strsplit(mcmc_cfg$hypparams %||% "10,10,10,30", ",")))))
  if (length(prior_type) != 4 || length(hypparams) != 4 || any(!is.finite(hypparams))) stop("prior.control$type and hypparams must each have four values.", call. = FALSE)
  mcmc_control <- list(
    n.burnin = as.integer(mcmc_cfg$n.burnin %||% 10000),
    n.iteration = as.integer(mcmc_cfg$n.iteration %||% 40000),
    n.thin = as.integer(mcmc_cfg$n.thin %||% 30),
    seed = as.integer(mcmc_cfg$seed %||% 1234)
  )
  prior_control <- list(type = prior_type, hypparams = hypparams,
                        ssvs.index = ssvs_index, ssvs.g = as.numeric(trait_cfg$ssvs.g %||% 1e-6),
                        ssvs.traitsindex = ssvs_traitsindex)
  write.csv(data.frame(response = colnames(Ymat), family = fam, trial_size = if (length(trial_size) == 1) trial_size else trial_size,
                       stringsAsFactors = FALSE), file.path("tables", "family_trial_size.csv"), row.names = FALSE)
  if (!is.null(X_design)) write.csv(X_design, file.path("data", "X_design_matrix.csv"), row.names = TRUE)
  if (!is.null(traits)) write.csv(traits, file.path("data", "traits_design_matrix.csv"), row.names = TRUE)

  dep_errors <- character()
  if (!requireNamespace("rjags", quietly = TRUE)) {
    dep_errors <- c(dep_errors, "R package rjags is not available.")
  } else {
    rjags_load <- tryCatch({ suppressPackageStartupMessages(library(rjags)); TRUE },
                           error = function(e) conditionMessage(e))
    if (!isTRUE(rjags_load)) dep_errors <- c(dep_errors, paste0("rjags cannot load JAGS: ", rjags_load))
  }
  if (!requireNamespace("R2jags", quietly = TRUE)) dep_errors <- c(dep_errors, "R package R2jags is not available.")
  if (!requireNamespace("boral", quietly = TRUE)) dep_errors <- c(dep_errors, "R package boral is not installed or cannot load.")
  writeLines(if (length(dep_errors) == 0) "JAGS/rjags/R2jags/boral dependency check passed." else dep_errors,
             file.path("diagnostics", "JAGS_status.txt"))
  if (length(dep_errors) > 0) {
    set_status_value("fit_failed")
    add_status_error(dep_errors)
    writeLines(dep_errors, file.path("diagnostics", "boral_dependency_error.txt"))
    dep_notes <- rep("", 4)
    dep_notes[seq_len(min(4, length(dep_errors)))] <- dep_errors[seq_len(min(4, length(dep_errors)))]
    write.csv(data.frame(parameter = c("boral", "rjags", "R2jags", "JAGS"), status = "missing_or_unloadable",
                         notes = dep_notes, stringsAsFactors = FALSE),
              file.path("diagnostics", "dependency_status.csv"), row.names = FALSE)
    stop(paste(dep_errors, collapse = "; "), call. = FALSE)
  }

  fam_arg <- if (length(unique(fam)) == 1) unique(fam) else fam
  formula_arg <- if (!is.null(X_clean)) as.formula(trimws(model_cfg$formula.X %||% "~ .")) else NULL
  X_arg <- if (!is.null(X_clean)) X_clean else NULL
  Xind <- parse_xind(model_cfg$X.ind %||% "", ncol(Ymat), if (is.null(X_design)) 0 else ncol(X_design))
  model_name <- basename(model_cfg$model.name %||% "jagsboralmodel.txt")
  if (!nzchar(model_name)) model_name <- "jagsboralmodel.txt"
  model_name <- file.path("jags", model_name)
  fit_args <- list(
    y = Ymat,
    X = X_arg,
    formula.X = formula_arg,
    X.ind = Xind,
    traits = traits,
    which.traits = which_traits,
    family = fam_arg,
    trial.size = trial_size,
    lv.control = lv_control,
    row.eff = model_cfg$row.eff %||% "none",
    row.ids = rowids,
    ranef.ids = ranefids,
    offset = offset,
    save.model = isTRUE(trait_cfg$save.model %||% FALSE) || isTRUE(mcmc_cfg$save_mcmc_samples %||% FALSE),
    calc.ics = isTRUE(mcmc_cfg$calc.ics %||% FALSE),
    mcmc.control = mcmc_control,
    prior.control = prior_control,
    do.fit = isTRUE(model_cfg$do.fit %||% TRUE),
    model.name = model_name
  )
  fit_args <- fit_args[!vapply(fit_args, is.null, logical(1))]
  capture.output(str(fit_args, max.level = 2), file = file.path("diagnostics", "boral_fit_arguments.txt"))
  suppressPackageStartupMessages(library(boral))
  fit <- do.call(boral::boral, fit_args)
  if (isTRUE(out_cfg$save_model %||% TRUE)) saveRDS(fit, file.path("models", "boral_model.rds"))
  if (file.exists(model_name) && isTRUE(out_cfg$save_jags %||% TRUE)) {
    jags_dest <- file.path("jags", "jagsboralmodel.txt")
    if (!identical(normalizePath(model_name, winslash = "/", mustWork = FALSE),
                   normalizePath(jags_dest, winslash = "/", mustWork = FALSE))) {
      file.copy(model_name, jags_dest, overwrite = TRUE)
    }
  }
  if (!isTRUE(model_cfg$do.fit %||% TRUE)) {
    writeLines(c(
      "boral model was defined with do.fit=FALSE.",
      "JAGS model code and the boral model definition were exported; posterior summaries are intentionally skipped."
    ), file.path("results", "MODEL_DEFINED_NOT_FITTED.txt"))
    set_status_value("model_defined")
    TRUE
  } else {
  if (isTRUE(diag_cfg$summary %||% TRUE)) {
    capture.output(print(summary(fit)), file = file.path("tables", "summary_boral.txt"))
    summ <- safe_step("summary.boral", summary(fit))
    if (!is.null(summ)) {
      capture.output(str(summ), file = file.path("tables", "summary_boral_structure.txt"))
    }
  }
  safe_step("tidyboral", {
    if (isTRUE(diag_cfg$tidyboral %||% TRUE) && exists("tidyboral", where = asNamespace("boral"), inherits = FALSE)) {
      tb <- boral::tidyboral(fit)
      saveRDS(tb, file.path("tables", "tidyboral.rds"))
      capture.output(str(tb), file = file.path("tables", "tidyboral_structure.txt"))
    }
  })
  safe_step("hpd intervals", {
    if (isTRUE(mcmc_cfg$save_hpd %||% TRUE) && !is.null(fit$hpdintervals)) {
      saveRDS(fit$hpdintervals, file.path("tables", "hpd_intervals.rds"))
      capture.output(str(fit$hpdintervals), file = file.path("tables", "hpd_intervals_structure.txt"))
    } else {
      write.csv(data.frame(output = "hpd_intervals", status = "not_available_for_this_model_or_settings", stringsAsFactors = FALSE),
                file.path("tables", "hpd_intervals_manifest.csv"), row.names = FALSE)
    }
  })
  safe_step("mcmc samples", {
    if (isTRUE(mcmc_cfg$save_mcmc_samples %||% TRUE) && exists("get.mcmcsamples", where = asNamespace("boral"), inherits = FALSE)) {
      smp <- boral::get.mcmcsamples(fit)
      saveRDS(smp, file.path("mcmc", "mcmc_samples.rds"))
      capture.output(summary(smp), file = file.path("mcmc", "mcmc_samples_summary.txt"))
    } else if (!is.null(fit$fit.mcmc)) {
      saveRDS(fit$fit.mcmc, file.path("mcmc", "mcmc_samples.rds"))
    }
  })
  safe_step("fitted values", {
    if (isTRUE(diag_cfg$fitted %||% TRUE)) {
      fv <- boral::fitted.boral(fit)
      write.csv(flatten_matrix(fv, "fitted"), file.path("predictions", "fitted_values.csv"), row.names = FALSE)
      write.csv(flatten_matrix(fv, "predicted_mean"), file.path("standard", "predictions_long.csv"), row.names = FALSE)
    }
  })
  safe_step("predictions", {
    if (isTRUE(diag_cfg$predict %||% TRUE)) {
      new_clean <- clean_predictors(newdata_raw)
      if (!is.null(new_clean)) {
        new_design <- make_design(new_clean, model_cfg$formula.X %||% "~ .")
        can_new_predict <- !is.null(new_design) &&
          (fit$lv.control$type %||% "independent") == "independent" &&
          (fit$row.eff %||% "none") == "none" &&
          is.null(fit$ranef.ids)
        if (isTRUE(can_new_predict)) {
          pr <- boral::predict.boral(fit, newX = new_design, predict.type = "marginal", scale = "response")
          saveRDS(pr, file.path("predictions", "predictions.rds"))
          write.csv(flatten_matrix(pr, "predicted"), file.path("predictions", "predictions.csv"), row.names = FALSE)
        } else {
          write.csv(data.frame(output = "newdata_predictions", status = "skipped_requires_new_latent_distance_or_random_effect_ids", stringsAsFactors = FALSE),
                    file.path("predictions", "prediction_manifest.csv"), row.names = FALSE)
        }
      } else {
        pr <- boral::predict.boral(fit, scale = "response")
        saveRDS(pr, file.path("predictions", "predictions.rds"))
        write.csv(flatten_matrix(pr, "predicted"), file.path("predictions", "predictions.csv"), row.names = FALSE)
      }
    }
  })
  safe_step("enviro_cor", {
    if (isTRUE(diag_cfg$enviro_cor %||% TRUE) && exists("get.enviro.cor", where = asNamespace("boral"), inherits = FALSE) && !is.null(fit$X.coefs.mean)) {
      ec <- boral::get.enviro.cor(fit)
      write.csv(flatten_matrix(ec, "correlation"), file.path("tables", "enviro_cor.csv"), row.names = FALSE)
    } else if (isTRUE(diag_cfg$enviro_cor %||% TRUE)) {
      write.csv(data.frame(output = "enviro_cor", status = "not_available_without_X_coefficients", stringsAsFactors = FALSE),
                file.path("tables", "enviro_cor_manifest.csv"), row.names = FALSE)
    }
  })
  safe_step("residual_cor", {
    if (isTRUE(diag_cfg$residual_cor %||% TRUE) && exists("get.residual.cor", where = asNamespace("boral"), inherits = FALSE) && (fit$num.lv %||% 0) > 0) {
      rc <- boral::get.residual.cor(fit)
      write.csv(flatten_matrix(rc, "correlation"), file.path("tables", "residual_cor.csv"), row.names = FALSE)
      assoc <- flatten_matrix(rc, "estimate")
      write.csv(data.frame(engine = "boral", assoc, association_type = "residual_latent_variable", stringsAsFactors = FALSE),
                file.path("standard", "associations_long.csv"), row.names = FALSE)
    } else if (isTRUE(diag_cfg$residual_cor %||% TRUE)) {
      write.csv(data.frame(output = "residual_cor", status = "not_available_without_latent_variables", stringsAsFactors = FALSE),
                file.path("tables", "residual_cor_manifest.csv"), row.names = FALSE)
    }
  })
  safe_step("DIC", {
    if (isTRUE(mcmc_cfg$save_dic %||% TRUE) && !is.null(fit$dic)) {
      write.csv(flatten_matrix(fit$dic, "value"), file.path("tables", "dic.csv"), row.names = FALSE)
    }
    if (!is.null(fit$logLik)) write.csv(flatten_matrix(fit$logLik, "value"), file.path("tables", "logLik_conditional.csv"), row.names = FALSE)
    if (!is.null(fit$measures)) write.csv(flatten_matrix(fit$measures, "value"), file.path("tables", "measures.csv"), row.names = FALSE)
  })
  safe_step("variance partition", {
    if (isTRUE(diag_cfg$varpart %||% FALSE) && exists("calc.varpart", where = asNamespace("boral"), inherits = FALSE)) {
      vp <- boral::calc.varpart(fit)
      saveRDS(vp, file.path("tables", "varpart.rds"))
      write.csv(flatten_matrix(vp, "value"), file.path("tables", "varpart.csv"), row.names = FALSE)
    }
  })
  safe_step("plots", {
    if (isTRUE(out_cfg$save_plots %||% TRUE)) {
      if (isTRUE(diag_cfg$residual_plot %||% TRUE)) {
        grDevices::pdf(file.path("plots", "residual_diagnostics.pdf")); try(plot(fit), silent = TRUE); grDevices::dev.off()
      }
      if (isTRUE(diag_cfg$lvsplot %||% TRUE) && num_lv > 0) {
        grDevices::pdf(file.path("ordination", "lvsplot.pdf")); try(boral::lvsplot(fit), silent = TRUE); grDevices::dev.off()
      }
      if (isTRUE(diag_cfg$coefsplot %||% TRUE)) {
        grDevices::pdf(file.path("plots", "coefsplot.pdf")); try(boral::coefsplot(fit), silent = TRUE); grDevices::dev.off()
      }
      if (isTRUE(diag_cfg$ranefsplot %||% FALSE) && !is.null(ranefids)) {
        grDevices::pdf(file.path("plots", "ranefsplot.pdf")); try(boral::ranefsplot(fit), silent = TRUE); grDevices::dev.off()
      }
    }
  })
  safe_step("direct object tables", {
    direct_names <- c("X.coefs.median", "X.coefs.mean", "lv.coefs.median", "lv.mean", "traits.coefs.median",
                      "row.coefs", "row.sigma", "ranef.coefs.median", "ranef.sigma.median",
                      "ssvs.indcoefs.mean", "ssvs.traitscoefs.mean")
    for (nm in direct_names) {
      if (!is.null(fit[[nm]])) {
        target_dir <- if (grepl("row|ranef", nm)) "random_effects" else if (grepl("ssvs", nm)) "variable_selection" else if (grepl("lv", nm)) "ordination" else "tables"
        saveRDS(fit[[nm]], file.path(target_dir, paste0(nm, ".rds")))
        capture.output(str(fit[[nm]]), file = file.path(target_dir, paste0(nm, "_structure.txt")))
      }
    }
  })
  set_status_value("fitted")
  }
  TRUE
}, error = function(e) {
  set_status_value("fit_failed")
  if (length(status$errors %||% character()) == 0) add_status_error(conditionMessage(e))
  writeLines(conditionMessage(e), file.path("diagnostics", "boral_fit_error.txt"))
  FALSE
})

write.csv(data.frame(
  Section = c("Configuration", "Inputs", "JAGS model", "Model object", "MCMC samples", "Posterior summaries", "Ordination", "Residual diagnostics", "Coefficients", "Correlations", "Random effects", "Variable selection", "Prediction", "Fit / model comparison", "Diagnostics", "Report"),
  Expected_file_or_folder = c("used_config.yml", "inputs/data copies", "jags/jagsboralmodel.txt", "models/boral_model.rds", "mcmc/mcmc_samples.rds", "tables/summary_boral.*", "ordination/*", "residuals/* and plots/residual_diagnostics.pdf", "tables/coefficient_* and plots/coefsplot.pdf", "tables/*cor.csv", "random_effects/*", "variable_selection/*", "predictions/*", "tables/dic.csv/logLik/measures/varpart", "diagnostics/*", "report/boral_report.html"),
  stringsAsFactors = FALSE
), file.path("tables", "boral_result_workflow_map.csv"), row.names = FALSE)

write_standard(Y, X_raw)
write_status()
write_report(if (status$status == "fit_failed") paste(c(status$warnings, status$errors), collapse = "; ") else "boral run completed or model was defined.")
write.csv(data.frame(file = list.files(".", recursive = TRUE), stringsAsFactors = FALSE),
          file.path("standard", "output_manifest.csv"), row.names = FALSE)
write_empty_readmes()

if (!fit_or_fail) quit(status = 1)
}"
