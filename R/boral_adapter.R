safe_step <- function(label, expr) {
  tryCatch(expr, error = function(e) {
    msg <- paste0(label, " failed: ", conditionMessage(e))
    add_status_warning(msg)
    writeLines(msg, file.path("diagnostics", paste0(gsub("[^A-Za-z0-9]+", "_", label), "_warning.txt")))
    NULL
  })
}

